// Returns exact topology for char (case-sensitive) or fallback
function getGlyphTopology(char) {
  if (GLYPH_TOPOLOGIES[char]) {
    return GLYPH_TOPOLOGIES[char];
  }
  const upper = char.toUpperCase();
  if (GLYPH_TOPOLOGIES[upper]) {
    return GLYPH_TOPOLOGIES[upper];
  }
  // Clean fallback box
  return {
    pins: [
      {x: 0.15, y: 0.38},
      {x: 0.85, y: 0.38},
      {x: 0.85, y: 1.0},
      {x: 0.15, y: 1.0}
    ],
    strokes: [[0, 1, 2, 3, 0]]
  };
}

window.getGlyphTopology = getGlyphTopology;
